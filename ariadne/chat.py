"""Our own chat: a conversation bound to one session that can talk, look things up, and submit - never work.

The design's rule (docs/DESIGN-RESET.md) is that a conversational surface composes and submits; it never does the
task. That is enforced **by construction**, not by a hook: the chat home is launched with a toolset list that has no
files, no terminal, no code, no browser - only the Ariadne task verbs (`mcp-ariadne_tasks`), skills, clarify, and
read-only search. The old `ariadne_gate` hook is retired: refusing tools after the model chose them was a patch
for a container we no longer use (docs/FRONTEND.md).

Two doors share it: `ariadne chat` (a terminal Hermes session in this home) and the console's chat panel, which posts
one message at a time to `/api/chat`. The turn runner is injectable, so every test runs without a model.
"""
import json
import os
import subprocess
from pathlib import Path

from . import flows as flowlib
from . import paths, serving, service
from .errors import TaskError

HOME_NAME = "chat"
TOOLSETS = ["mcp-ariadne_tasks", "skills", "clarify", "search"]   # no file, terminal, code, browser or connectors


class ChatError(RuntimeError):
    pass


TURN = """This is the conversation attached to Ariadne session "{session}". Ariadne is a local task harness: a brief
becomes a backbrief, a person signs it off, a worker executes it on a local model, and check gates decide.
{context}
The person says:
{message}

Rules for this conversation:
- You may talk, look things up (read-only), and give Ariadne a task with submit_task; the person signs off on it.
- You cannot do the work yourself: you have no files, terminal, code or browser. Never paste work as if you had done
  it, and never suggest signing in to some other service.
- When the person wants work done, agree the brief and the check gates (how we know it is done), then call
  submit_task with a flow and a model from get_choices.
- Answer about this session from the task store; say plainly when you do not know.
"""


def chat_model() -> str:
    """The agent model the chat talks with: the first installed one in the approved catalog."""
    from . import models as modellib
    try:
        cat = modellib.load()
    except modellib.ModelError as e:
        raise ChatError(str(e))
    for m in cat.models.values():
        if m.kind == "agent" and m.installed():
            return m.name
    raise ChatError("no approved agent model is installed; fetch one (`ariadne models install <name>`) or ask the "
                    "person to pick another")


def compile_home():
    """Write the chat's Hermes home: the task MCP server, a model, the local endpoint, and no doing-tools at launch."""
    home = paths.HOMES / HOME_NAME
    home.mkdir(parents=True, exist_ok=True)
    cfg = json.loads(json.dumps(flowlib.BASE_CONFIG))
    cfg["model"]["default"] = chat_model()
    try:
        cfg["model"]["base_url"] = serving.endpoint()
    except serving.ServingError as e:
        raise ChatError(f"no usable model server: {e}")
    cfg["mcp_servers"] = {"ariadne_tasks": {"command": str(paths.VENV_PY if paths.VENV_PY.exists() else paths.PYTHON),
                                           "args": ["-m", "ariadne.tasks_mcp"],
                                           "env": {"PYTHONPATH": str(paths.ROOT)}, "timeout": 120}}
    cfg["plugins"] = {"enabled": [], "auto_update_check_hours": 0}
    from . import yamlio
    (home / "config.yaml").write_text("# Generated by ariadne.chat - do not edit.\n" + yamlio.safe_dump(cfg), encoding="utf-8")
    return home


def session_context(session: str, store=None) -> str:
    """What the chat knows about the session without touching a file: its tasks and their states, newest first."""
    if not session:
        return "No session is selected: answer about Ariadne itself, and ask which session they mean before submitting."
    rows = [t for t in service.tasks(60, store=store) if (t.get("session") or "") == session]
    if not rows:
        return f'Session "{session}" has no tasks yet.'
    lines = [f'Session "{session}" - its most recent tasks:']
    for t in rows[:20]:
        lines.append(f"- {t['id']}  {t['status']:<16} {t.get('flow') or '-':<8} {(t.get('text') or '').splitlines()[0][:90]}")
    return "\n".join(lines)


def run_turn(home, prompt, session="", model=""):
    """One Hermes turn in the chat home. No doing-tools: the toolset list is the construction (no files, no terminal)."""
    from .worker import RunResult, _clean_output
    cmd = [str(paths.HERMES_EXE), "chat", "--query", prompt, "-Q", "--source", "tool", "-t", ",".join(TOOLSETS),
           "--max-turns", "12", "--run-budget", "600", "-m", model or chat_model()]
    if session:
        cmd += ["-c", session, "--create-if-missing"]
    env = dict(os.environ, HERMES_HOME=str(home), PYTHONIOENCODING="utf-8")
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace",
                           stdin=subprocess.DEVNULL, timeout=900, env=env)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise ChatError(f"the chat model did not answer: {e}")
    return RunResult(_clean_output(p.stdout or ""), p.returncode, str(home / "logs"))


def ask(message: str, session: str = "", store=None, runner=None, model: str = "") -> str:
    """One turn of the conversation. Raises ChatError (the caller turns it into a 400), never returns a traceback."""
    message = (message or "").strip()
    if not message:
        raise ChatError("say something first: the chat has nothing to answer")
    home = compile_home()
    prompt = TURN.format(session=session or "(none)", context=session_context(session, store), message=message)
    r = (runner or run_turn)(home, prompt, session, model)
    if getattr(r, "exit_code", 0) != 0 or not (getattr(r, "text", "") or "").strip():
        raise ChatError(f"the chat model did not answer (exit {getattr(r, 'exit_code', '?')}); the models may be down")
    return r.text


def main(argv=None):
    """`ariadne chat [--session NAME]`: the terminal door onto the same home and the same rule."""
    import sys
    argv = list(sys.argv[1:] if argv is None else argv)
    home = compile_home()
    cmd = [str(paths.HERMES_EXE), "chat", "-s", "ariadne-tasks", "--pass-session-id", "-t", ",".join(TOOLSETS)]
    if "--session" in argv:
        i = argv.index("--session")
        name, argv = argv[i + 1], argv[:i] + argv[i + 2:]
        cmd += ["-c", name, "--create-if-missing"]
    print(f"chat home: {home}   (tools: {', '.join(TOOLSETS)} - it can submit tasks, not do them)")
    return subprocess.call(cmd + argv, env=dict(os.environ, HERMES_HOME=str(home)))
