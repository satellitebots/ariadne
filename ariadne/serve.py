"""Local model server: llama-swap with serving/llama-swap.yaml rendered for this machine. One model on the GPU."""
import json
import os
import signal
import subprocess
import sys
import time

from . import deps, llm, paths

PID_FILE = paths.STATE / "llama-swap.pid"
CONFIG = paths.STATE / "llama-swap.yaml"


def render_config():
    server = deps.find_bin("llama.cpp", "llama-server")
    if not server:
        sys.exit("llama-server is missing: run  python -m ariadne install")
    wrapper = paths.ROOT / "serving" / "llama_server_exclusive.py"
    q = lambda p: f'"{p}"'
    from . import models, yamlio
    text = (paths.ROOT / "serving" / "llama-swap.yaml").read_text(encoding="utf-8")
    cfg = yamlio.safe_load(text.replace("{{SERVER}}", f"{q(paths.VENV_PY)} {q(wrapper)} {q(server)}"))
    cfg["models"] = models.swap_entries()
    # Embedding models run beside the agent model instead of swapping it out: an ingest calls `embed` thousands of
    # times, and each swap reloaded a 22 GB model (the RAG build spent an hour doing that). They run on the CPU
    # (-ngl 0 in the catalog), stay loaded (persistent) and never unload anything (not exclusive).
    side = [m.name for m in models.load().models.values() if m.kind == "embed"]
    if side:
        cfg["groups"] = {"side": {"swap": False, "exclusive": False, "persistent": True, "members": side}}
    paths.ensure()
    CONFIG.write_text("# Generated by python -m ariadne serve - do not edit.\n" + yamlio.safe_dump(cfg), encoding="utf-8")
    return CONFIG


def apply_if_changed():
    """Re-render the model server config when it would change (e.g. a new resource profile). llama-swap reloads it
    and restarts its models, so only call this between tasks."""
    if not CONFIG.exists():
        return False
    before = CONFIG.read_text(encoding="utf-8")
    render_config()
    changed = CONFIG.read_text(encoding="utf-8") != before
    if not changed:
        return False
    print("model server config updated (resource profile or catalog)", flush=True)
    return True


def _pid():
    try:
        return json.loads(PID_FILE.read_text())["pid"]
    except (OSError, ValueError, KeyError):
        return None


def _kill_strays():
    """llama-swap / llama-server processes started from serving/bin that outlived their parent."""
    if paths.WINDOWS:
        ps = (f"Get-Process llama-swap,llama-server -ErrorAction SilentlyContinue | "
              f"Where-Object {{ $_.Path -like '{paths.BIN}*' }} | Stop-Process -Force")
        subprocess.run(["powershell", "-NoProfile", "-Command", ps], capture_output=True)
    else:
        subprocess.run(["pkill", "-f", str(paths.BIN)], capture_output=True)


def stop():
    """Stop the model server we started. A LAN box or a local Ollama is not ours to stop."""
    from . import paths, serving
    try:
        srv = serving.active()
    except serving.ServingError:
        srv = {"kind": "llama-server"}
    if srv.get("kind") != "llama-server":
        print(f"the active server is {srv.get('kind')} at {srv.get('url') or '(no url)'}; nothing of ours to stop")
        return 0
    pid = _pid()
    if pid:
        try:
            if paths.WINDOWS:
                subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"], capture_output=True)
            else:
                os.killpg(pid, signal.SIGTERM)
        except (OSError, ProcessLookupError):
            pass
        PID_FILE.unlink(missing_ok=True)
    _kill_strays()
    print("models stopped")
    return 0


def start(listen=None, wait=60):
    """Start our llama-server when it is the active server; an Ollama or a LAN box only has to answer.

    The choice comes from `serving.active()` (docs/MODELS.md): there is no point starting a local binary when the
    person pointed Ariadne at a GPU box, and pretending to "start" it would hide that it is down.
    """
    listen = listen or f"127.0.0.1:{paths.PORT_MODELS}"
    from . import serving
    try:
        srv = serving.active()
    except serving.ServingError as e:
        sys.exit(str(e))
    target = serving.endpoint(srv)
    if llm.is_up(target):
        print(f"models already up on {target}")
        return 0
    if srv.get("kind") != "llama-server":
        sys.exit(f"the active model server is {srv.get('kind')} at {srv.get('url') or '(no url)'}, and it is not "
                 f"answering {target}.\n  start it there, or switch:  python -m ariadne server setup")
    swap = deps.find_bin("llama-swap", "llama-swap")
    if not swap:
        sys.exit("llama-swap is missing: run  python -m ariadne install")
    from .resources import detect_at_boot
    detect_at_boot()  # measure the machine now: the profile's GPU/RAM limits follow the hardware actually present
    cfg = render_config()
    paths.ensure()
    # -watch-config: a model fetched later (after a sign-off) is picked up when render_config() rewrites the file.
    # Started outside the caller's session (procs.py), so a closed terminal or dropped remote session cannot kill it.
    from .procs import spawn_detached
    pid = spawn_detached([swap, "-config", cfg, "-listen", listen, "-watch-config"], paths.LOGS / "llama-swap.log",
                         paths.ROOT)
    PID_FILE.write_text(json.dumps({"pid": pid}))
    for _ in range(wait):
        time.sleep(1)
        if llm.is_up(f"http://{listen}/v1"):
            print(f"models up on http://{listen}/v1 (log {paths.LOGS / 'llama-swap.log'})")
            return 0
    sys.exit(f"llama-swap did not come up; see {paths.LOGS / 'llama-swap.log'}")
